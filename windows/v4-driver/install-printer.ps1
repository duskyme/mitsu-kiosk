#Requires -RunAsAdministrator
#Requires -Version 5.1
<#
.SYNOPSIS
  Stage V4 Phase 1 package (incl. render filter when built), optionally add TCP port + queue, seed ICC.

.PARAMETER SkipDriverStore
  Only stage files / create port+queue assuming driver already present.

.PARAMETER SkipQueue
  Only stage + note pnputil; do not create port/printer.

.PARAMETER BridgePort
  RAW TCP port for Standard TCP/IP Port (default 9100).

.PARAMETER PrinterName
  Queue display name.

.PARAMETER BuildFilter
  Run filter\build.ps1 before staging if the DLL is missing.

.PARAMETER Sign
  Build a catalog with Inf2Cat and sign it with a WDK/test cert (default subject WDKTestCert*).

.PARAMETER CertSubject
  Certificate subject substring for SignTool /n (CurrentUser\My).
#>
param(
    [switch]$SkipDriverStore,
    [switch]$SkipQueue,
    [switch]$BuildFilter,
    [switch]$Sign,
    [string]$CertSubject = "WDKTestCert",
    [int]$BridgePort = 9100,
    [string]$PrinterName = "Mitsubishi CP-9550DW-S (V4)",
    [string]$PortName = "CP9550_TCP_9100"
)

$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$stage = Join-Path $here "_stage"
$bridgeProj = Join-Path $here "..\Cp9550Native\Cp9550SpoolBridge\Cp9550SpoolBridge.csproj"
$filterDll = Join-Path $here "filter\_out\Release\Cp9550RenderFilter.dll"
$spoolTool = Join-Path $here "filter\_out\Release\cp9550-spooltool.exe"
$pipeline = Join-Path $here "pipeline\CP9550-pipelineconfig.xml"

Write-Host "== CP-9550 V4 Phase 1 install =="
Write-Host "Package root: $here"

if ($BuildFilter -or -not (Test-Path $filterDll)) {
    Write-Host "Building render filter..."
    & (Join-Path $here "filter\build.ps1") -Configuration Release
}
if (-not (Test-Path $filterDll)) {
    throw "Missing $filterDll - build filter\build.ps1 before install."
}

# Flat stage so INF SourceDisksFiles resolve next to the INF.
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
New-Item -ItemType Directory -Force -Path $stage | Out-Null
Copy-Item (Join-Path $here "CP9550-manifest.ini") $stage
Copy-Item (Join-Path $here "gpd\CP9550.gpd") $stage
Copy-Item $pipeline $stage
Copy-Item (Join-Path $here "color\CP955_01.ICC") $stage
Copy-Item $filterDll $stage

# Rewrite INF for flat stage (all files disk 1). Keep in sync with inf\CP9550DW-S-Printer.inf.
# IHV filter DLL is CopyFiles-only - never RequiredFiles (event 235).
$flatInf = @"
; Generated by install-printer.ps1 - flat stage layout (Phase 1).
; See inf\CP9550DW-S-Printer.inf for packaging notes (IHV filter via CopyFiles, GPD cursor cmds).
[Version]
Signature   = "`$Windows NT`$"
Provider    = %ManufacturerName%
Class       = Printer
ClassGUID   = {4D36E979-E325-11CE-BFC1-08002BE10318}
CatalogFile = CP9550DW-S-Printer.cat
ClassVer    = 4.0
