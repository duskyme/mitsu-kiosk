#Requires -RunAsAdministrator
#Requires -Version 5.1
<#
.SYNOPSIS
  Stage V4 spike package, optionally add TCP port + printer queue, seed ICC.

.PARAMETER SkipDriverStore
  Only stage files / create port+queue assuming driver already present.

.PARAMETER SkipQueue
  Only stage + note pnputil; do not create port/printer.

.PARAMETER BridgePort
  RAW TCP port for Standard TCP/IP Port (default 9100).

.PARAMETER PrinterName
  Queue display name.
#>
param(
    [switch]$SkipDriverStore,
    [switch]$SkipQueue,
    [int]$BridgePort = 9100,
    [string]$PrinterName = "Mitsubishi CP-9550DW-S (V4)",
    [string]$PortName = "CP9550_TCP_9100"
)

$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$stage = Join-Path $here "_stage"
$bridgeProj = Join-Path $here "..\Cp9550Native\Cp9550SpoolBridge\Cp9550SpoolBridge.csproj"

Write-Host "== CP-9550 V4 spike install =="
Write-Host "Package root: $here"

# Flat stage so INF SourceDisksFiles resolve next to the INF.
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
New-Item -ItemType Directory -Force -Path $stage | Out-Null
Copy-Item (Join-Path $here "inf\CP9550DW-S-Printer.inf") (Join-Path $stage "CP9550DW-S-Printer.inf")
Copy-Item (Join-Path $here "CP9550-manifest.ini") $stage
Copy-Item (Join-Path $here "gpd\CP9550.gpd") $stage
Copy-Item (Join-Path $here "pipeline\cp9550-pipelineconfig.xml") $stage
Copy-Item (Join-Path $here "color\CP955_01.ICC") $stage

# Rewrite INF for flat stage (all files disk 1).
$flatInf = @"
; Generated by install-printer.ps1 from spike sources — flat stage layout.
[Version]
Signature   = "`$Windows NT`$"
Provider    = %ManufacturerName%
Class       = Printer
ClassGUID   = {4D36E979-E325-11CE-BFC1-08002BE10318}
CatalogFile = CP9550DW-S-Printer.cat
ClassVer    = 4.0
DriverVer   = 11/01/2026,0.1.0.0
PnpLockdown = 1

[Manufacturer]
%ManufacturerName% = Standard,NTamd64

[Standard.NTamd64]
"Mitsubishi CP-9550DW-S (V4)" = Install, {A55C9550-06D3-4A55-9D77-C9550D0500A1}

[Install]
CopyFiles = DriverFiles, ColorFiles

[DriverFiles]
CP9550.gpd
CP9550-manifest.ini
cp9550-pipelineconfig.xml

[ColorFiles]
CP955_01.ICC

[DestinationDirs]
DefaultDestDir = 66000
ColorFiles     = 66003

[SourceDisksNames.amd64]
1 = %Location%,,,

[SourceDisksFiles]
CP9550.gpd = 1
CP9550-manifest.ini = 1
cp9550-pipelineconfig.xml = 1
CP955_01.ICC = 1

[Strings]
ManufacturerName = "CP9550 Native (community)"
Location         = "CP-9550 V4 spike package"
"@
Set-Content -LiteralPath (Join-Path $stage "CP9550DW-S-Printer.inf") -Value $flatInf -Encoding ASCII

Write-Host "Staged flat package → $stage"
Write-Host ""
Write-Host "NOTE: IHV render filter DLL is not built yet. pnputil may warn or the"
Write-Host "queue will not convert XPS→native spool. Bridge S1 still prints known spools."
Write-Host ""

if (-not $SkipDriverStore) {
    Write-Host "Attempting pnputil /add-driver (unsigned — needs testsigning or test cert)…"
    $inf = Join-Path $stage "CP9550DW-S-Printer.inf"
    & pnputil /add-driver $inf /install
    Write-Host "pnputil exit: $LASTEXITCODE"
    if ($LASTEXITCODE -ne 0) {
        Write-Warning @"
Driver store add failed (expected without catalog/testsigning).
Enable test signing or sign the package, then re-run.
bcdedit /set testsigning on   # reboot required
"@
    }
}

if (-not $SkipQueue) {
    # Standard TCP/IP RAW port → bridge
    $existingPort = Get-PrinterPort -Name $PortName -ErrorAction SilentlyContinue
    if (-not $existingPort) {
        Write-Host "Creating TCP port $PortName → 127.0.0.1:$BridgePort (RAW)"
        Add-PrinterPort -Name $PortName -PrinterHostAddress "127.0.0.1" -PortNumber $BridgePort -ErrorAction Stop
    } else {
        Write-Host "Port $PortName already exists"
    }

    $existingPrinter = Get-Printer -Name $PrinterName -ErrorAction SilentlyContinue
    if (-not $existingPrinter) {
        Write-Host "Adding printer queue '$PrinterName'"
        try {
            Add-Printer -Name $PrinterName -DriverName "Mitsubishi CP-9550DW-S (V4)" -PortName $PortName
        } catch {
            Write-Warning "Add-Printer failed (driver name may be missing from store): $($_.Exception.Message)"
            Write-Host "After a successful signed/testsigned pnputil install, re-run with -SkipDriverStore"
        }
    } else {
        Write-Host "Printer '$PrinterName' already exists"
    }

    if (Get-Printer -Name $PrinterName -ErrorAction SilentlyContinue) {
        Write-Host "Associating base ICC…"
        & (Join-Path $here "associate-icc.ps1") -Mode reset -PrinterName $PrinterName
    }
}

Write-Host ""
Write-Host "Bridge (keep running before jobs):"
Write-Host "  dotnet run --project `"$bridgeProj`" -- --port $BridgePort --save-dir `"$here\_capture`""
Write-Host "One-shot known spool:"
Write-Host "  dotnet run --project `"$bridgeProj`" -- --spool-file JOB.bin"
Write-Host "WinUSB device INF remains: windows\install.ps1"
Write-Host "Done."
