#Requires -RunAsAdministrator
#Requires -Version 5.1
<#
.SYNOPSIS
  Stage V4 Phase 1 package (incl. render filter when built), optionally add TCP port + queue, seed ICC.

.PARAMETER SkipDriverStore
  Only stage files / create port+queue assuming driver already present.

.PARAMETER SkipQueue
  Only stage + note pnputil; do not create port/printer.

.PARAMETER BridgePort
  RAW TCP port for Standard TCP/IP Port (default 9100).

.PARAMETER PrinterName
  Queue display name.

.PARAMETER BuildFilter
  Run filter\build.ps1 before staging if the DLL is missing.

.PARAMETER Sign
  Build a catalog with Inf2Cat and sign it with a WDK/test cert (default subject WDKTestCert*).

.PARAMETER CertSubject
  Certificate subject substring for SignTool /n (CurrentUser\My).

.PARAMETER ForceReplace
  Remove existing cp9550dw-s-printer.inf packages from the DriverStore before pnputil
  (needed when you must force a re-add; plain re-add of the same package returns pnputil 259).
#>
param(
    [switch]$SkipDriverStore,
    [switch]$SkipQueue,
    [switch]$BuildFilter,
    [switch]$Sign,
    [switch]$ForceReplace,
    [string]$CertSubject = "WDKTestCert",
    [int]$BridgePort = 9100,
    [string]$PrinterName = "Mitsubishi CP-9550DW-S (V4)",
    [string]$PortName = "CP9550_TCP_9100"
)

$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$stage = Join-Path $here "_stage"
$bridgeProj = Join-Path $here "..\Cp9550Native\Cp9550SpoolBridge\Cp9550SpoolBridge.csproj"
$filterDll = Join-Path $here "filter\_out\Release\Cp9550RenderFilter.dll"
$spoolTool = Join-Path $here "filter\_out\Release\cp9550-spooltool.exe"
$pipeline = Join-Path $here "pipeline\CP9550-pipelineconfig.xml"

Write-Host "== CP-9550 V4 Phase 1 install =="
Write-Host "Package root: $here"

if ($BuildFilter -or -not (Test-Path $filterDll)) {
    Write-Host "Building render filter..."
    & (Join-Path $here "filter\build.ps1") -Configuration Release
}
if (-not (Test-Path $filterDll)) {
    throw "Missing $filterDll - build filter\build.ps1 before install."
}

# Flat stage so INF SourceDisksFiles resolve next to the INF.
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
New-Item -ItemType Directory -Force -Path $stage | Out-Null
Copy-Item (Join-Path $here "CP9550-manifest.ini") $stage
Copy-Item (Join-Path $here "gpd\CP9550.gpd") $stage
Copy-Item $pipeline $stage
Copy-Item (Join-Path $here "color\CP955_01.ICC") $stage
Copy-Item $filterDll $stage

# Rewrite INF for flat stage (all files disk 1). Keep in sync with inf\CP9550DW-S-Printer.inf.
# IHV filter DLL is CopyFiles-only - never RequiredFiles (event 235).
# Pipeline XML must be well-formed (no "--" inside comments -> event 372).
$flatInf = @"
; Generated by install-printer.ps1 - flat stage layout (Phase 1).
; See inf\CP9550DW-S-Printer.inf for packaging notes (IHV filter via CopyFiles, GPD cursor cmds).
; Pipeline XML comments must not contain "--" (event 372 / 0x80004005).
[Version]
Signature   = "`$Windows NT`$"
Provider    = %ManufacturerName%
Class       = Printer
ClassGUID   = {4D36E979-E325-11CE-BFC1-08002BE10318}
CatalogFile = CP9550DW-S-Printer.cat
ClassVer    = 4.0
DriverVer   = 11/01/2026,0.3.10.0
PnpLockdown = 1

[Manufacturer]
%ManufacturerName% = Standard,NTamd64

[Standard.NTamd64]
"Mitsubishi CP-9550DW-S (V4)" = Install, {A55C9550-06D3-4A55-9D77-C9550D0500A1}

[Install]
CopyFiles = DriverFiles, ColorFiles

[Install.Services]
AddService = , %SPSVCINST_ASSOCSERVICE%

[DriverFiles]
CP9550.gpd
CP9550-manifest.ini
CP9550-pipelineconfig.xml
Cp9550RenderFilter.dll

[ColorFiles]
CP955_01.ICC

[DestinationDirs]
DefaultDestDir = 13
ColorFiles     = 66003

[SourceDisksNames.amd64]
1 = %Location%,,,

[SourceDisksFiles]
CP9550.gpd = 1
CP9550-manifest.ini = 1
CP9550-pipelineconfig.xml = 1
Cp9550RenderFilter.dll = 1
CP955_01.ICC = 1

[PrinterPackageInstallation.amd64]
PackageAware = TRUE

[Strings]
ManufacturerName = "CP9550 Native (community)"
Location         = "CP-9550 V4 Phase 1 package"
SPSVCINST_ASSOCSERVICE = 0x00000002
"@
Set-Content -LiteralPath (Join-Path $stage "CP9550DW-S-Printer.inf") -Value $flatInf -Encoding ASCII

Write-Host "Staged flat package -> $stage (includes Cp9550RenderFilter.dll in pipeline)"
Write-Host ""

function Find-KitTool([string]$Name) {
    $kit = "${env:ProgramFiles(x86)}\Windows Kits\10\bin"
    if (-not (Test-Path $kit)) { return $null }
    Get-ChildItem $kit -Recurse -Filter $Name -ErrorAction SilentlyContinue |
        Where-Object { $_.FullName -match '\\x64\\|\\x86\\' } |
        Sort-Object FullName -Descending |
        Select-Object -First 1 -ExpandProperty FullName
}

function Get-Cp9550DriverRepos {
    Get-ChildItem "$env:SystemRoot\System32\DriverStore\FileRepository" -Directory -Filter "cp9550dw-s-printer*" -ErrorAction SilentlyContinue |
        Sort-Object LastWriteTime -Descending
}

function Get-Cp9550PublishedOems {
    $enum = pnputil /enum-drivers
    $pubs = @()
    $cur = $null
    foreach ($line in $enum) {
        if ($line -match "Published Name:\s+(\S+)") { $cur = $Matches[1] }
        if ($line -match "Original Name:\s+cp9550dw-s-printer\.inf" -and $cur) {
            $pubs += $cur
            $cur = $null
        }
    }
    return $pubs
}

function Test-TestSigningEnabled {
    # Avoid bcdedit {current} quoting pitfalls on localized shells.
    $out = & bcdedit /enum 2>$null | Out-String
    if ($out -match "(?im)^\s*testsigning\s+Yes\s*$") { return $true }
    return $false
}

function Assert-WdkTestCertReady([string]$SubjectSubstr) {
    $my = @(Get-ChildItem Cert:\CurrentUser\My -ErrorAction SilentlyContinue |
        Where-Object { $_.Subject -like "*$SubjectSubstr*" -and $_.HasPrivateKey })
    if ($my.Count -eq 0) {
        throw "No CurrentUser\My cert matching '*$SubjectSubstr*' with a private key. Create/import a WDK test cert first."
    }
    $tp = $my[0].Thumbprint
    $root = Get-ChildItem Cert:\LocalMachine\Root -ErrorAction SilentlyContinue | Where-Object Thumbprint -eq $tp
    $pub = Get-ChildItem Cert:\LocalMachine\TrustedPublisher -ErrorAction SilentlyContinue | Where-Object Thumbprint -eq $tp
    if (-not $root -or -not $pub) {
        Write-Warning @"
WDK test cert '$($my[0].Subject)' is in CurrentUser\My but not fully trusted for DriverStore.
Import the same cert (Admin) into LocalMachine\Root and LocalMachine\TrustedPublisher, e.g.:
  Export-Certificate -Cert Cert:\CurrentUser\My\$tp -FilePath `$env:TEMP\wdk.cer
  Import-Certificate -FilePath `$env:TEMP\wdk.cer -CertStoreLocation Cert:\LocalMachine\Root
  Import-Certificate -FilePath `$env:TEMP\wdk.cer -CertStoreLocation Cert:\LocalMachine\TrustedPublisher
"@
    } else {
        Write-Host "WDK test cert OK: $($my[0].Subject) (Root+TrustedPublisher)"
    }
    return $my[0]
}

if ($Sign) {
    $null = Assert-WdkTestCertReady $CertSubject
    $inf2cat = Find-KitTool "Inf2Cat.exe"
    $signtool = Find-KitTool "signtool.exe"
    if (-not $inf2cat -or -not $signtool) {
        throw "Sign requested but Inf2Cat/signtool not found under Windows Kits\10\bin"
    }
    Write-Host "Inf2Cat..."
    & $inf2cat /driver:$stage /os:10_X64
    if ($LASTEXITCODE -ne 0) { throw "Inf2Cat failed ($LASTEXITCODE)" }
    $cat = Get-ChildItem $stage -Filter "*.cat" | Select-Object -First 1
    if (-not $cat) { throw "Inf2Cat produced no .cat in $stage" }
    $catPath = Join-Path $stage "CP9550DW-S-Printer.cat"
    if ($cat.FullName -ne $catPath) {
        Move-Item -LiteralPath $cat.FullName -Destination $catPath -Force
    }
    Write-Host "SignTool /fd SHA256 /n $CertSubject..."
    & $signtool sign /fd SHA256 /s My /n $CertSubject /tr http://timestamp.digicert.com /td SHA256 $catPath
    if ($LASTEXITCODE -ne 0) {
        Write-Warning "Timestamped sign failed; retrying without timestamp"
        & $signtool sign /fd SHA256 /s My /n $CertSubject $catPath
    }
    if ($LASTEXITCODE -ne 0) { throw "SignTool failed ($LASTEXITCODE)" }
    & $signtool verify /pa $catPath
    if ($LASTEXITCODE -ne 0) { throw "SignTool verify failed ($LASTEXITCODE)" }
    $sig = Get-AuthenticodeSignature $catPath
    Write-Host "Catalog signature: $($sig.Status) ($($sig.SignerCertificate.Subject))"
}

if (-not $SkipDriverStore) {
    $ts = Test-TestSigningEnabled
    Write-Host ("testsigning: " + $(if ($ts) { "ON" } else { "OFF (OK if WDK test cert is in Root+TrustedPublisher)" }))

    if ($ForceReplace) {
        Write-Host "ForceReplace: removing queue/driver and published cp9550dw-s-printer packages..."
        Get-Printer -Name $PrinterName -ErrorAction SilentlyContinue | Remove-Printer -Confirm:$false -ErrorAction SilentlyContinue
        try { Remove-PrinterDriver -Name "Mitsubishi CP-9550DW-S (V4)" -ErrorAction Stop } catch {}
        foreach ($oem in (Get-Cp9550PublishedOems)) {
            Write-Host "  pnputil /delete-driver $oem /uninstall /force"
            & pnputil /delete-driver $oem /uninstall /force | Out-Null
        }
    }

    Write-Host "Attempting pnputil /add-driver (needs Admin + signed cat; testsigning OR trusted WDK cert)..."
    $inf = Join-Path $stage "CP9550DW-S-Printer.inf"
    $pnpOut = & pnputil /add-driver $inf /install 2>&1 | Out-String
    $pnpExit = $LASTEXITCODE
    Write-Host $pnpOut.TrimEnd()
    Write-Host "pnputil exit: $pnpExit"

    # 0 = added. 259 (ERROR_NO_MORE_ITEMS) with Added=0 usually means identical package already in store.
    $alreadyPresent = ($pnpExit -eq 259) -or (($pnpOut -match "(?i)Added driver packages:\s*0") -and ($pnpOut -match "(?i)Total driver packages:\s*1"))
    $repo = Get-Cp9550DriverRepos | Select-Object -First 1
    if ($pnpExit -ne 0 -and -not ($alreadyPresent -and $repo)) {
        Write-Warning @"
Driver store add failed (exit $pnpExit).
Checklist:
  1) Re-run elevated with -Sign (WDKTestCert in CurrentUser\My).
  2) Cert also in LocalMachine\Root + TrustedPublisher (see warning above).
  3) Or: bcdedit /set testsigning on  (reboot), then re-run -Sign.
  4) To force a clean re-add: .\install-printer.ps1 -Sign -ForceReplace
"@
    } else {
        if ($alreadyPresent -and $pnpExit -ne 0) {
            Write-Host "pnputil ${pnpExit}: package already in DriverStore (not a signing failure). Refreshing printer driver binding..."
        }
        if (-not $repo) {
            Write-Warning "No cp9550dw-s-printer* folder under DriverStore\FileRepository after pnputil."
        } else {
            $repoInf = Join-Path $repo.FullName "CP9550DW-S-Printer.inf"
            $repoPipe = Join-Path $repo.FullName "CP9550-pipelineconfig.xml"
            $verLine = (Select-String -Path $repoInf -Pattern "DriverVer" | Select-Object -First 1).Line
            Write-Host "DriverStore: $($repo.FullName)"
            Write-Host "  $verLine"
            try {
                $xd = New-Object System.Xml.XmlDocument
                $xd.Load($repoPipe)
                Write-Host "  pipeline XML: PARSE_OK (Filters present)"
            } catch {
                Write-Warning "  pipeline XML: PARSE_FAIL $($_.Exception.Message)"
            }
            Write-Host "Add-PrinterDriver from $($repo.FullName)"
            try {
                Add-PrinterDriver -Name "Mitsubishi CP-9550DW-S (V4)" -InfPath $repoInf -ErrorAction Stop
            } catch {
                Write-Host "Add-PrinterDriver: $($_.Exception.Message)"
            }
        }
    }
}
if (-not $SkipQueue) {
    $existingPort = Get-PrinterPort -Name $PortName -ErrorAction SilentlyContinue
    if (-not $existingPort) {
        Write-Host "Creating TCP port $PortName -> 127.0.0.1:$BridgePort (RAW)"
        Add-PrinterPort -Name $PortName -PrinterHostAddress "127.0.0.1" -PortNumber $BridgePort -ErrorAction Stop
    } else {
        Write-Host "Port $PortName already exists"
    }

    $existingPrinter = Get-Printer -Name $PrinterName -ErrorAction SilentlyContinue
    if (-not $existingPrinter) {
        Write-Host "Adding printer queue '$PrinterName'"
        try {
            Add-Printer -Name $PrinterName -DriverName "Mitsubishi CP-9550DW-S (V4)" -PortName $PortName -ErrorAction Stop
        } catch {
            Write-Warning "Add-Printer failed: $($_.Exception.Message)"
            Write-Host "After a successful signed/testsigned pnputil + Add-PrinterDriver, re-run with -SkipDriverStore"
        }
    } else {
        Write-Host "Printer '$PrinterName' already exists"
    }

    if (Get-Printer -Name $PrinterName -ErrorAction SilentlyContinue) {
        Write-Host "Associating base ICC..."
        & (Join-Path $here "associate-icc.ps1") -Mode reset -PrinterName $PrinterName
    }
}

Write-Host ""
Write-Host "Bridge (keep running before jobs):"
Write-Host "  dotnet run --project `"$bridgeProj`" -- --port $BridgePort --save-dir `"$here\_capture`""
Write-Host "Offline spool (no XPS queue):"
Write-Host "  & `"$spoolTool`" --solid 220 40 40 --out `"$here\_capture\job.bin`""
Write-Host "  dotnet run --project `"$bridgeProj`" -- --spool-file `"$here\_capture\job.bin`""
Write-Host "WinUSB device INF remains: windows\install.ps1"
Write-Host "Done."

